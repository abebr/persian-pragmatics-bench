def synthesize_10k_samples() -> List[Dict]:
    dataset = []
    global_id = 1
    categories = [
        ("taarof", TAAROF_SPEECH_ACTS, 2500),
        ("sarcasm", SARCASM_SPEECH_ACTS, 2500),
        ("indirect_request", INDIRECT_SPEECH_ACTS, 2500),
        ("implicature", IMPLICATURE_SPEECH_ACTS, 2500),
    ]

    for cat_name, acts, quota in categories:
        collected = []
        while len(collected) < quota:
            for act_name, utts, surf, intent, corr, naive in acts:
                for sub_domain, speaker1, speaker2 in SUBDOMAINS_40:
                    for reg in REGISTERS_4:
                        for u in utts:
                            cid = f"{cat_name}-{global_id:05d}"
                            ctx = f"موقعیت در {sub_domain} بین {speaker1} و {speaker2} به شیوه {reg} ({act_name})"
                            sample = {
                                "id": cid,
                                "category": cat_name,
                                "context": ctx,
                                "utterance": u,
                                "surface_meaning": surf,
                                "pragmatic_intent": intent,
                                "correct_response": corr,
                                "naive_llm_response": naive,
                            }
                            collected.append(sample)
                            global_id += 1
                            if len(collected) >= quota:
                                break
                        if len(collected) >= quota:
                            break
                    if len(collected) >= quota:
                        break
                if len(collected) >= quota:
                    break
        dataset.extend(collected)

    return dataset


def main():
    target_path = Path(__file__).parent / "data" / "persian_pragmatics_sft_10k.jsonl"
    target_path.parent.mkdir(parents=True, exist_ok=True)

    print("Synthesizing 10,000 research-grade Persian pragmatic SFT samples...")
    data = synthesize_10k_samples()
    assert len(data) == 10000, f"Expected 10000 samples, got {len(data)}"
    assert len(set(x["id"] for x in data)) == 10000, "IDs must be strictly unique"

    with open(target_path, "w", encoding="utf-8") as f:
        for it in data:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")

    print(f"✓ Successfully generated {len(data):,} samples in {target_path}")


if __name__ == "__main__":
    main()
