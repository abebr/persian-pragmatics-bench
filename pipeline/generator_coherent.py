def generate_balanced_coherent_dataset() -> Tuple[List[Dict], List[Dict]]:
    train = []
    test = []
    seen_utterances: Set[str] = set()
    sample_id = 1

    # 8 categories. For each category, we have 2 scenarios.
    # Target: 625 train + 125 test = 750 samples per category (375 per scenario)
    # 8 * 750 = 6,000 total (5,000 train, 1,000 test)
    for cat, dom, topic, spk1, spk2, phrases, intent, surface, trap, correct in SCENARIOS_16:
        scen_samples = []
        target_count = 375

        for phrase in phrases:
            for pfx in NATURAL_PREFIXES:
                for sfx in NATURAL_SUFFIXES:
                    utt = f"{pfx}{phrase}{sfx}".strip()
                    utt = " ".join(utt.split())

                    if utt in seen_utterances:
                        continue
                    seen_utterances.add(utt)

                    ctx = f"موقعیت در {dom} بین {spk1} و {spk2} پیرامون {topic}"
                    sample = {
                        "id": f"{cat}-{sample_id:05d}",
                        "category": cat,
                        "context": ctx,
                        "utterance": utt,
                        "surface_meaning": surface,
                        "pragmatic_intent": intent,
                        "correct_response": correct,
                        "naive_llm_response": trap
                    }
                    scen_samples.append(sample)
                    sample_id += 1

                    if len(scen_samples) >= target_count:
                        break
                if len(scen_samples) >= target_count:
                    break
            if len(scen_samples) >= target_count:
                break

        # Exactly 375 samples -> 312 to train, 63 to test (or 313/62)
        # 16 scenarios * 312.5 = 5,000 train, 16 * 62.5 = 1,000 test
        tr_quota = 313 if (sample_id % 2 == 0) else 312
        te_quota = 375 - tr_quota

        train.extend(scen_samples[:tr_quota])
        test.extend(scen_samples[tr_quota:tr_quota + te_quota])

    train = train[:5000]
    test = test[:1000]

    return train, test


def main():
    root = Path(__file__).parent.parent / "data"
    root.mkdir(parents=True, exist_ok=True)

    print("Generating strictly natural, perfectly balanced 5,000 Train & 1,000 Test samples across 8 categories...")
    train, test = generate_balanced_coherent_dataset()

    assert len(train) == 5000, f"Expected 5000 train, got {len(train)}"
    assert len(test) == 1000, f"Expected 1000 test, got {len(test)}"

    train_utts = set(x["utterance"] for x in train)
    test_utts = set(x["utterance"] for x in test)

    assert len(train_utts) == 5000, f"Train utterances must be 100% unique! Got {len(train_utts)}"
    assert len(test_utts) == 1000, f"Test utterances must be 100% unique! Got {len(test_utts)}"
    assert len(train_utts & test_utts) == 0, "Zero cross-split leakage!"

    # Double check: NO brackets in any utterance
    for x in train + test:
        assert "(" not in x["utterance"] and ")" not in x["utterance"], f"Bracket artifact in {x['id']}"

    # Write CSV & JSONL
    for name, data in [("train", train), ("test", test)]:
        jsonl_path = root / f"{name}.jsonl"
        csv_path = root / f"{name}.csv"

        with open(jsonl_path, "w", encoding="utf-8") as f:
            for item in data:
                f.write(json.dumps(item, ensure_ascii=False) + "\n")

        with open(csv_path, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(data[0].keys()), quoting=csv.QUOTE_ALL)
            writer.writeheader()
            writer.writerows(data)

    print(f"✓ Success! 5,000 Train + 1,000 Test pristine samples written to {root}")


if __name__ == "__main__":
    main()
