PREFIXES_8 = [
    "راستش رو بخوای", "والا خدمتتون عرض کنم", "ببین عزیز من", "با کمال احترام",
    "حقیقت ماجرا اینه که", "شرمنده اگه بد موقع میگم ولی", "توجه داشته باشید که", "اگر حمل بر جسارت نباشه"
]


def generate_6k_strictly_unique() -> Tuple[List[Dict], List[Dict]]:
    train = []
    test = []
    seen_utterances: Set[str] = set()
    sample_id = 1

    # Target: 5,000 train + 1,000 test = 6,000 total (750 per category)
    for cat_name, data in CATEGORY_TEMPLATES.items():
        cat_samples = []
        target_for_cat = 750

        for a_idx, act in enumerate(data["acts"]):
            for p_idx, phrase in enumerate(data["phrases"]):
                for d_idx, dom in enumerate(DOMAINS_25):
                    for r_idx, reg in enumerate(REGISTERS_4):
                        pfx = PREFIXES_8[(a_idx + p_idx + d_idx + r_idx) % len(PREFIXES_8)]
                        
                        # Generate unique natural utterance
                        utt = f"{pfx} {phrase} ({act})"
                        if utt in seen_utterances:
                            continue
                        seen_utterances.add(utt)

                        ctx = f"موقعیت در {dom} با لحن {reg} پیرامون {act}"
                        sample = {
                            "id": f"{cat_name}-{sample_id:05d}",
                            "category": cat_name,
                            "context": ctx,
                            "utterance": utt,
                            "surface_meaning": f"{data['surface']} (مربوط به {act})",
                            "pragmatic_intent": f"{data['intent']} (در بافت {act})",
                            "correct_response": data["correct"],
                            "naive_llm_response": data["trap"]
                        }
                        cat_samples.append(sample)
                        sample_id += 1

                        if len(cat_samples) >= target_for_cat:
                            break
                    if len(cat_samples) >= target_for_cat:
                        break
                if len(cat_samples) >= target_for_cat:
                    break
            if len(cat_samples) >= target_for_cat:
                break

        # Split 625 to train, 125 to test (8 * 625 = 5000 train, 8 * 125 = 1000 test)
        train.extend(cat_samples[:625])
        test.extend(cat_samples[625:750])

    return train, test


def main():
    root = Path(__file__).parent.parent / "data"
    root.mkdir(parents=True, exist_ok=True)

    print("Generating strictly unique 5,000 Train & 1,000 Test samples across 8 categories...")
    train, test = generate_6k_strictly_unique()

    assert len(train) == 5000, f"Expected 5000 train, got {len(train)}"
    assert len(test) == 1000, f"Expected 1000 test, got {len(test)}"

    train_utts = set(x["utterance"] for x in train)
    test_utts = set(x["utterance"] for x in test)

    assert len(train_utts) == 5000, f"Train utterances must be 100% unique! Got {len(train_utts)}"
    assert len(test_utts) == 1000, f"Test utterances must be 100% unique! Got {len(test_utts)}"
    assert len(train_utts & test_utts) == 0, "Cross-split leakage detected!"

    # Save CSV & JSONL
    for name, data in [("train", train), ("test", test)]:
        jsonl_path = root / f"{name}.jsonl"
        csv_path = root / f"{name}.csv"

        with open(jsonl_path, "w", encoding="utf-8") as f:
            for item in data:
                f.write(json.dumps(item, ensure_ascii=False) + "\n")

        with open(csv_path, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(data[0].keys()), quoting=csv.QUOTE_ALL)
            writer.writeheader()
            writer.writerows(data)

    print(f"✓ Success! 5,000 Train + 1,000 Test strictly unique samples written to {root}")


if __name__ == "__main__":
    main()
