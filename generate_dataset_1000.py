def generate_full_dataset(target_count: int = 1000) -> List[Dict]:
    dataset = []
    sample_id = 1

    configs = [
        ("taarof", TAAROF_CONFIGS),
        ("sarcasm", SARCASM_CONFIGS),
        ("indirect_request", INDIRECT_REQUEST_CONFIGS),
        ("implicature", IMPLICATURE_CONFIGS),
    ]

    target_per_cat = target_count // len(configs)

    for cat_name, cat_list in configs:
        cat_samples = []
        while len(cat_samples) < target_per_cat:
            for group in cat_list:
                for d in DOMAINS:
                    for r in REGISTERS:
                        for utt in group["utterances"]:
                            cid = f"{cat_name}-{sample_id:04d}"
                            context = group["context_tpl"].format(domain=d, reg=r)
                            
                            sample = {
                                "id": cid,
                                "category": cat_name,
                                "context": context,
                                "utterance": utt,
                                "surface_meaning": group["surface"],
                                "pragmatic_intent": group["intent"],
                                "correct_response": group["correct"],
                                "naive_llm_response": group["naive"],
                            }
                            cat_samples.append(sample)
                            sample_id += 1
                            if len(cat_samples) >= target_per_cat:
                                break
                        if len(cat_samples) >= target_per_cat:
                            break
                    if len(cat_samples) >= target_per_cat:
                        break
                if len(cat_samples) >= target_per_cat:
                    break
        dataset.extend(cat_samples)

    return dataset


def main():
    target_path = Path(__file__).parent / "data" / "persian_pragmatics_1000.jsonl"
    target_path.parent.mkdir(parents=True, exist_ok=True)

    data = generate_full_dataset(1000)
    with open(target_path, "w", encoding="utf-8") as f:
        for it in data:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")

    print(f"✓ Successfully generated {len(data)} pragmatic samples in {target_path}")


if __name__ == "__main__":
    main()
